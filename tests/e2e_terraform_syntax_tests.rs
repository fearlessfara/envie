#[test]
fn test_variables_and_outputs_structure() {
    if !terraform_available() {
        eprintln!("Skipping test: terraform not available");
        return;
    }

    let temp_dir = TempDir::new().unwrap();
    let unit_dir = temp_dir.path().join("units/vars_test");
    std::fs::create_dir_all(&unit_dir).unwrap();

    let main_tf = r#"terraform {
  required_version = ">= 1.0"
}

variable "envie_workspace" {
  type        = string
  description = "Workspace name"
}

variable "instance_count" {
  type    = number
  default = 1
}

variable "tags" {
  type = map(string)
  default = {
    Environment = "test"
  }
}

locals {
  common_tags = merge(var.tags, {
    Workspace = var.envie_workspace
  })
}

output "instance_count" {
  value = var.instance_count
}

output "tags" {
  value = local.common_tags
}
"#;
    std::fs::write(unit_dir.join("main.tf"), main_tf).unwrap();

    // Verify formatting is valid
    let fmt_result = run_terraform_fmt_check(&unit_dir);
    assert!(
        fmt_result.is_ok(),
        "Variable and output declarations should be valid: {:?}",
        fmt_result
    );

    // Verify content structure
    let content = std::fs::read_to_string(unit_dir.join("main.tf")).unwrap();
    assert!(content.contains("variable \"envie_workspace\""));
    assert!(content.contains("variable \"instance_count\""));
    assert!(content.contains("variable \"tags\""));
    assert!(content.contains("output \"instance_count\""));
    assert!(content.contains("output \"tags\""));
    assert!(content.contains("locals {"));
}
